#!/usr/bin/env node
/**
 * Embed original QuantumNous factory plugin.js sources and evaluated meta
 * objects for the workerd factory registry. Runtime cannot import those ESM
 * files as text without a custom loader, so this writes a TypeScript module
 * consumed by src/task-plugin-factory.ts.
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const tasksDir = join(root, "../src/task-plugins/tasks");
const outPath = join(root, "../src/task-plugin-factory-data.ts");

const entries = await readdir(tasksDir, { withFileTypes: true });
const keys = entries
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const sources = {};
const metas = {};
const hashes = {};
const icons = {};

for (const key of keys) {
  const sourcePath = join(tasksDir, key, "plugin.js");
  const source = await readFile(sourcePath, "utf8");
  sources[key] = source;
  hashes[key] = createHash("sha256").update(source, "utf8").digest("hex");
  const mod = await import(pathToFileURL(sourcePath).href);
  metas[key] = JSON.parse(JSON.stringify(mod.meta));
  for (const name of ["icon.svg", "icon.png"]) {
    try {
      const bytes = await readFile(join(tasksDir, key, name));
      const mediaType = name.endsWith(".svg") ? "image/svg+xml" : "image/png";
      icons[key] = {
        mediaType,
        dataUri: `data:${mediaType};base64,${bytes.toString("base64")}`,
      };
      break;
    } catch {
      /* no sidecar */
    }
  }
}

const banner = `/* eslint-disable */
/** Generated by scripts/embed-task-plugins.mjs from original QuantumNous factory plugins. Do not edit by hand. */

`;

const body =
  banner +
  `export const FACTORY_TASK_PLUGIN_KEYS = ${JSON.stringify(keys)} as const;\n\n` +
  `export const FACTORY_TASK_PLUGIN_SOURCES: Record<string, string> = ${JSON.stringify(sources)};\n\n` +
  `export const FACTORY_TASK_PLUGIN_METAS: Record<string, Record<string, unknown>> = ${JSON.stringify(metas)};\n\n` +
  `export const FACTORY_TASK_PLUGIN_HASHES: Record<string, string> = ${JSON.stringify(hashes)};\n\n` +
  `export const FACTORY_TASK_PLUGIN_ICONS: Record<string, { mediaType: string; dataUri: string }> = ${JSON.stringify(icons)};\n`;

await writeFile(outPath, body);
console.log(`wrote ${outPath} keys=${keys.join(",")}`);

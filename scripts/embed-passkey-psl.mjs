#!/usr/bin/env node
/**
 * Embed golang.org/x/net v0.55.0 publicsuffix rules (PSL git d6c92f1)
 * so NormalizePasskeyRPID can match original EffectiveTLDPlusOne / PublicSuffix.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const root = dirname(fileURLToPath(import.meta.url));
const outPath = join(root, "../src/passkey-psl-data.ts");
const defaultTable = join(
  homedir(),
  "go/pkg/mod/golang.org/x/net@v0.55.0/publicsuffix/table_test.go",
);
const tablePath = process.env.PASSKEY_PSL_TABLE || defaultTable;
const source = await readFile(tablePath, "utf8");
const icannMatch = source.match(/const numICANNRules = (\d+)/);
if (!icannMatch) throw new Error("numICANNRules not found in " + tablePath);
const numICANN = Number(icannMatch[1]);
const start = source.indexOf("var rules = [...]string{");
if (start < 0) throw new Error("rules table not found");
const block = source.slice(start);
const rules = [...block.matchAll(/"([^"]*)"/g)].map((m) => m[1]);
if (rules.length <= numICANN) throw new Error("too few PSL rules: " + rules.length);
if (rules[numICANN - 1] !== "zuerich" || rules[numICANN] !== "co.krd") {
  throw new Error("PSL ICANN/private boundary mismatch");
}

const banner = `/* eslint-disable */
/** Generated by scripts/embed-passkey-psl.mjs from golang.org/x/net v0.55.0 publicsuffix rules (PSL git d6c92f1). Do not edit by hand. */

`;

const body =
  banner +
  `export const PASSKEY_PSL_VERSION = "publicsuffix.org's public_suffix_list.dat, git revision d6c92f1bbb7433e5db7b8405c25d4035fb8ff376 (2026-02-06T07:36:33Z)";\n\n` +
  `export const PASSKEY_PSL_NUM_ICANN = ${numICANN};\n\n` +
  `export const PASSKEY_PSL_RULES = ${JSON.stringify(rules.join("\n"))};\n`;

await writeFile(outPath, body);
console.log(`wrote ${outPath} rules=${rules.length} icann=${numICANN}`);
